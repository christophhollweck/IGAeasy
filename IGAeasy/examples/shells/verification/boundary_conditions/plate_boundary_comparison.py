"""Clamped RM plate: strong, penalty and symmetric Nitsche conditions."""
import numpy as np
import matplotlib.pyplot as plt
from shapely.geometry import box, LineString
from IGAeasy.geometry import get_geometry
from IGAeasy.splines.THBSplines.hierarchical_space import HierarchicalSpace
from IGAeasy.splines.LRSplines.lr_spline import LRSpline
from IGAeasy.elements import RMshell6p, RMshell5p, RMshell5p_v2
from IGAeasy.material import LinearElasticMaterial
from IGAeasy.numerical_integration import assign_gp_and_properties
from IGAeasy.constraints.shell_weak import WeakRM6Boundary, WeakRM5Boundary
from IGAeasy.constraints.boundary_selection import select_patch_boundary
from IGAeasy.loads import SurfaceLoad
from IGAeasy.assembler import MatrixAssembler, VectorAssembler
from IGAeasy.solver.direct_solver import solve
from IGAeasy.error_norms.surface_norms import SurfaceL2Quadrature, SurfaceDirectorL2Quadrature

n = 2
p = 3
n_refinements = 3
formulations = ['RM6', 'RM5']
methods = ['strong', 'penalty', 'nitsche']
reference_kind = 'manufactured'  # 'uniform': compare weak solutions with strong on the same grid.
family = 'THB'


def polynomial(s):
    return s*s*(1-s)**2, 2*s-6*s*s+4*s**3, 2-12*s+12*s*s


def run_level(current, formulation='RM6', degree=3, kind='manufactured', family='THB',
              method_names=None):
    selected_methods = methods if method_names is None else method_names
    if family not in ('THB','LR'):
        raise ValueError('family must be THB or LR')
    if kind not in ('manufactured', 'uniform'):
        raise ValueError('kind must be manufactured or uniform')
    module = {'RM6': RMshell6p, 'RM5': RMshell5p, 'RM5_v2': RMshell5p_v2}[formulation]
    dof = 6 if formulation == 'RM6' else 5
    E, nu, t, amplitude = 10920., .3, .1, .01
    shear = (5/6)*E*t/(2*(1+nu))
    # The manufactured solution has w=A*f(u)*f(v), independent director=0.
    # Body torque balances the shear generated by grad(w); it is not a pure
    # pressure benchmark. Uniform pressure is a separate selectable case.
    def body(u, v):
        if kind == 'uniform':
            return np.r_[0., 0., -1., np.zeros(dof-3)]
        a, b = polynomial(u), polynomial(v)
        dx, dy = amplitude*a[1]*b[0], amplitude*a[0]*b[1]
        q = -shear*amplitude*(a[2]*b[0]+a[0]*b[2])
        moments = [-shear*dy, shear*dx, 0.] if dof == 6 else [shear*dx, shear*dy]
        return np.r_[0., 0., q, moments]
    def displacement(x, y, z):
        return np.array([0., 0., amplitude*polynomial(x)[0]*polynomial(y)[0]])
    geo = get_geometry.surface(current, current, 1, 1, 1, 1, degree-1, degree, distortion=0, n_waves=0)
    rs = (HierarchicalSpace(*geo.knot_vectors, degree, geo.control_points) if family == 'THB'
          else LRSpline(degree, *geo.knot_vectors, geo.control_points))
    assign_gp_and_properties(rs, material_model=LinearElasticMaterial(E, nu, 1.),
                             properties={'t': t, 'rho': 1.}, full_quad=True)
    shell, rule, load = module.RMShell(), np.polynomial.legendre.leggauss(3), SurfaceLoad(dof, body)
    for cell in rs.elements:
        if dof == 6:
            shell.element_routine(cell, rule)
        else:
            shell.element_routine(cell)
        cell.f_el += load.integrate_contribution(cell, dof)
    bulk = MatrixAssembler(dof_per_cp=dof).assemble(rs, 'K_el', use_sparse=True)
    force = VectorAssembler(dof_per_cp=dof).assemble(rs, 'f_el')
    fixed_ids = set().union(*(select_patch_boundary(rs, edge) for edge in ('umin', 'umax', 'vmin', 'vmax')))
    fixed = [dof*i+j for i in fixed_ids for j in range(dof)]
    free = np.setdiff1d(np.arange(len(force)), fixed)
    strong = np.zeros_like(force)
    strong[free] = solve(bulk[free, :][:, free], force[free], scaling=True)
    norm = SurfaceL2Quadrature(rs, order=degree+3)
    director = SurfaceDirectorL2Quadrature(rs, formulation, order=degree+3)
    line = LineString(box(0., 0., 1., 1.).exterior.coords)
    def make_boundary(method, penalty=None):
        options = dict(method=method, penalty=penalty, safety_factor=400. if method == 'penalty' else 4.)
        return (WeakRM6Boundary(line, lambda x,y,z: np.zeros(6), rule, **options)
            if dof == 6 else WeakRM5Boundary(line, lambda x,y,z: np.zeros(6), formulation, **options))
    trace_boundary = make_boundary('penalty', penalty=1.)
    for cell in rs.elements:
        cell.study_trace, _, _ = trace_boundary.integrate_contribution(cell)
    trace_matrix = MatrixAssembler(dof_per_cp=dof).assemble(rs, 'study_trace', use_sparse=True)
    # Rigid virtual motions extract physical global force/moment resultants.
    rigid = np.zeros((len(force), 6))
    for basis in rs.basis:
        start = dof*basis.id
        rigid[start:start+3, :3] = np.eye(3)
        for j, omega in enumerate(np.eye(3)):
            rigid[start:start+3, 3+j] = np.cross(omega, basis.cp)
            rigid[start+3:start+dof, 3+j] = omega if dof == 6 else np.cross(omega, [0., 0., 1.])[:2]
    results = []
    for method in selected_methods:
        gamma = 0.
        boundary_matrix = bulk*0.
        boundary_rhs = np.zeros_like(force)
        if method == 'strong':
            solution = strong
            reaction = bulk@solution-force
        else:
            boundary = make_boundary(method)
            for cell in rs.elements:
                matrix, rhs, bound = boundary.integrate_contribution(cell)
                cell.study_boundary_matrix, cell.study_boundary_rhs = matrix, rhs
                gamma = max(gamma, bound)
            boundary_matrix = MatrixAssembler(dof_per_cp=dof).assemble(rs, 'study_boundary_matrix', use_sparse=True)
            boundary_rhs = VectorAssembler(dof_per_cp=dof).assemble(rs, 'study_boundary_rhs')
            solution = solve(bulk+boundary_matrix, force+boundary_rhs, scaling=True)
            # This is the full discrete boundary-work vector, including adjoint
            # terms, not a pointwise traction. Rigid virtual work gives resultants.
            reaction = boundary_rhs-boundary_matrix@solution
        coefficients = solution.reshape(-1, dof)
        reference = displacement if kind == 'manufactured' else strong.reshape(-1, dof)[:, :3]
        director_reference = (lambda x,y,z: np.zeros(3)) if kind == 'manufactured' else strong.reshape(-1, dof)
        energy, external, boundary_work = .5*solution@(bulk@solution), solution@force, solution@reaction
        # Integral f^2=1/630 and integral (f')^2=2/105 on [0,1].
        exact_energy = shear*amplitude**2/33075 if kind == 'manufactured' else np.nan
        balance = rigid.T@(force+reaction)
        rowscale = max(np.linalg.norm(rigid.T@force), np.linalg.norm(force), 1e-300)
        results.append(dict(method=method, formulation=formulation, n=current, h=1/current,
            l2=norm.error(coefficients[:, :3], reference),
            director_l2=director.error(coefficients, director_reference), gamma=gamma,
            center=sum(b(.5,.5)*coefficients[b.id,2] for b in rs.basis),
            internal_energy=energy, external_work=external, boundary_work=boundary_work,
            energy_error=abs(energy-exact_energy),
            energy_balance=abs(2*energy-external-boundary_work)/max(abs(2*energy),abs(external),1e-300),
            boundary_trace_l2=np.sqrt(max(solution@(trace_matrix@solution), 0.)),
            force_balance=np.linalg.norm(balance[:3])/rowscale,
            moment_balance=np.linalg.norm(balance[3:])/rowscale,
            reaction_resultants=rigid.T@reaction, applied_resultants=rigid.T@force))
    return results


def main(show=True, *, formulations=formulations, methods=methods, family=family,
         n_refinements=n_refinements):
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    results = []
    for formulation in formulations:
        rows = []
        for level in range(n_refinements+1):
            current = n*2**level
            print(f'{formulation}: {current} x {current}...', flush=True)
            for row in run_level(current, formulation, p, reference_kind, family, method_names=methods):
                rows.append(row)
                print(f"{row['method']}: L2={row['l2']:.3e}, director={row['director_l2']:.3e}, "
                      f"force balance={row['force_balance']:.2e}, energy balance={row['energy_balance']:.2e}", flush=True)
        results.extend(rows)
        for method in methods:
            if reference_kind == 'uniform' and method == 'strong':
                continue
            selected = [r for r in rows if r['method'] == method]
            for ax, key in zip(axes, ('l2', 'director_l2')):
                ax.loglog([r['h'] for r in selected], [r[key] for r in selected], 'o-', label=f'{formulation} {method}')
    labels = ('Displacement L2 error', 'Director L2 error') if reference_kind == 'manufactured' else (
        'Displacement L2 vs strong (same mesh)', 'Director L2 vs strong (same mesh)')
    for ax, label in zip(axes, labels):
        ax.set_xlabel('Element size h')
        ax.set_ylabel(label)
        ax.grid(True, which='both')
        ax.legend(fontsize=7)
    fig.tight_layout()
    if show:
        plt.show()
    else:
        fig.canvas.draw()
    return results


if __name__ == '__main__':
    main()
